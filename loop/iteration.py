fruits_price = {
    "Apple": 250,
    "Banana": 80,
    "Orange": 180,
    "Mango": 300,
    "Grapes": 220
}

for i in fruits_price:
    print(i)

print("\n")

for i in fruits_price.keys():
    print(i )

for i in fruits_price.items():
    print(i)

print("\n")

for i , j in fruits_price.items():
    print(i)
    print(j)


